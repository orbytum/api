ALTER TABLE evento ALTER COLUMN descricao TYPE VARCHAR(1000);
ALTER TABLE evento ALTER COLUMN url TYPE VARCHAR(500);
ALTER TABLE evento ALTER COLUMN dth_fim DROP NOT NULL;
ALTER TABLE evento ALTER COLUMN is_online SET DEFAULT false;

ALTER TABLE evento DROP CONSTRAINT IF EXISTS fk_evento_on_grupo;
ALTER TABLE evento ADD CONSTRAINT fk_evento_on_grupo FOREIGN KEY (grupo_id) REFERENCES grupo (id);

ALTER TABLE evento DROP CONSTRAINT IF EXISTS fk_evento_on_criador;
ALTER TABLE evento ADD CONSTRAINT fk_evento_on_criador FOREIGN KEY (criador_id) REFERENCES usuario (id);

CREATE TABLE IF NOT EXISTS evento_participante
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    evento_id           BIGINT                                  NOT NULL,
    usuario_id          BIGINT,
    nome                VARCHAR(255)                            NOT NULL,
    presenca_confirmada BOOLEAN                                 NOT NULL DEFAULT false,
    CONSTRAINT pk_evento_participante PRIMARY KEY (id),
    CONSTRAINT fk_evento_participante_on_evento FOREIGN KEY (evento_id) REFERENCES evento (id) ON DELETE CASCADE,
    CONSTRAINT fk_evento_participante_on_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);
