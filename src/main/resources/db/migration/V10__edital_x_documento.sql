-- Vínculo entre editais e documentos.
CREATE TABLE IF NOT EXISTS edital_x_documento
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    edital_id    BIGINT                                  NOT NULL,
    documento_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_edital_x_documento PRIMARY KEY (id),
    CONSTRAINT uc_edital_x_documento UNIQUE (edital_id, documento_id),
    CONSTRAINT fk_edital_x_documento_on_edital FOREIGN KEY (edital_id) REFERENCES edital (id) ON DELETE CASCADE,
    CONSTRAINT fk_edital_x_documento_on_documento FOREIGN KEY (documento_id) REFERENCES documento (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_edital_x_documento_documento
    ON edital_x_documento (documento_id);
