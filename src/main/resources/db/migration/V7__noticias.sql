CREATE TABLE IF NOT EXISTS noticia
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid                  UUID,
    grupo_id              BIGINT,
    autor_id              BIGINT,
    aprovador_id          BIGINT,
    titulo                VARCHAR(255)                            NOT NULL,
    conteudo              TEXT                                    NOT NULL,
    referencia            VARCHAR(255),
    assunto               VARCHAR(255)                            NOT NULL,
    data_inicio_exibicao  TIMESTAMP WITHOUT TIME ZONE,
    data_fim_exibicao     TIMESTAMP WITHOUT TIME ZONE,
    motivo_rejeicao       VARCHAR(255),
    status                INTEGER,
    dth_registro          TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    dth_aprovacao         TIMESTAMP WITHOUT TIME ZONE,
    is_ativo              BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_noticia PRIMARY KEY (id)
);

ALTER TABLE noticia DROP CONSTRAINT IF EXISTS FK_NOTICIA_ON_GRUPO;
ALTER TABLE noticia ADD CONSTRAINT FK_NOTICIA_ON_GRUPO FOREIGN KEY (grupo_id) REFERENCES grupo (id);

ALTER TABLE noticia DROP CONSTRAINT IF EXISTS FK_NOTICIA_ON_AUTOR;
ALTER TABLE noticia ADD CONSTRAINT FK_NOTICIA_ON_AUTOR FOREIGN KEY (autor_id) REFERENCES usuario (id);

ALTER TABLE noticia DROP CONSTRAINT IF EXISTS FK_NOTICIA_ON_APROVADOR;
ALTER TABLE noticia ADD CONSTRAINT FK_NOTICIA_ON_APROVADOR FOREIGN KEY (aprovador_id) REFERENCES usuario (id);
